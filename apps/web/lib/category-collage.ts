// Hero background per TOP-LEVEL category (components/category-hero.tsx shows it whole): 9-11
// high-resolution CC0 / public-domain photos of that category's items, blended into one 2880x960
// image in the homepage banner's style by scripts/gen-category-heroes.mjs. The photos were found on
// Openverse and checked by eye, with off-topic shots, scans, brand logos, characters and real
// people left out; provenance is in scripts/category-background-sources.json. All 36 top-level
// categories are covered, Cars included (components/cars-landing.tsx uses its image the same way). The map is generated by
// that script (lib/category-backgrounds.json); file names carry a hash of the image, so a rebuilt
// image always gets a new URL and no cache keeps serving the old one.
import backgrounds from "./category-backgrounds.json";

const CATEGORY_BACKGROUNDS: Record<string, string> = backgrounds;

export function getCategoryCollageImage(topLevelStableKey: string | undefined): string | null {
  if (!topLevelStableKey) return null;
  return CATEGORY_BACKGROUNDS[topLevelStableKey] ?? null;
}
